import type { Order, Product, ProductColorOption, ProductVariant } from './types.js';

function buildVariants(
  skuPrefix: string,
  colors: ProductColorOption[],
  sizes: string[],
  stockMatrix: Record<string, number>,
): ProductVariant[] {
  const variants: ProductVariant[] = [];
  for (const color of colors) {
    for (const size of sizes) {
      const key = `${color.id}:${size}`;
      const stock = stockMatrix[key] ?? 6;
      variants.push({
        sku: `${skuPrefix}-${color.id.slice(0, 3).toUpperCase()}-${size.toUpperCase()}`,
        colorId: color.id,
        size,
        stock,
      });
    }
  }
  return variants;
}

